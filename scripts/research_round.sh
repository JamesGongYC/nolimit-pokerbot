#!/bin/sh
# Tune the new families (jam, Monte Carlo), build a league of strong bots, and
# tune the heuristic against that league (self-play / archived opponents).
set -e
cd "$(dirname "$0")/.."
export PYTHONUNBUFFERED=1
PY=${PY:-python3}; W=${W:-7}
$PY -m pokerbot.cli --workers $W optimize --base jam_25 --space allin --method cem --generations 8 --popsize 16 --screen-tables 300 --final-tables 1500 --seed 51 --out results/opt_jam
$PY -m pokerbot.cli --workers $W optimize --base mc_tag --method cem --generations 8 --popsize 12 --screen-tables 200 --final-tables 1200 --seed 52 --out results/opt_mc
$PY - <<'PY'
import json
def load(p, name):
    s = json.load(open(p)); s["name"] = name
    for k in ("train_cpu_s", "train_wall_s"): s.pop(k, None)
    return s
league = [[load("results/opt_heur/best.json", "L_heur1"), 3], [load("results/opt_heur2/best.json", "L_heur2"), 3],
          [load("results/opt_linear/best.json", "L_linear"), 2], [load("results/opt_eq2/best.json", "L_eq2"), 2],
          [load("results/opt_hybrid_h/best.json", "L_hybh"), 1], [load("results/opt_mc/best.json", "L_mc"), 2],
          [load("results/opt_jam/best.json", "L_jam"), 1], ["jam_nash", 1], ["heur_tag", 1]]
json.dump({"_comment": "LEAGUE: strong tuned bots (self-play/archive field). Generated by scripts/research_round.sh",
           "fields": {"league": league}}, open("configs/populations/league.json", "w"), indent=1)
print("league written")
PY
$PY -m pokerbot.cli --workers $W optimize --base results/opt_heur/best.json --fields configs/populations/league.json --method cem --generations 8 --popsize 16 --screen-tables 400 --final-tables 2000 --sigma 0.12 --seed 53 --out results/opt_heur_league
